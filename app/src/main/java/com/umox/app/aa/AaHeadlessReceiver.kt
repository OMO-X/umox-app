package com.umox.app.aa

import android.content.Context
import android.os.SystemClock
import android.util.Log
import java.io.ByteArrayOutputStream
import java.io.DataInputStream
import java.io.EOFException
import java.io.IOException
import java.io.OutputStream
import java.net.ConnectException
import java.net.InetSocketAddress
import java.net.Socket
import java.net.SocketException
import java.net.SocketTimeoutException
import java.util.concurrent.Executors
import java.util.concurrent.ScheduledExecutorService
import java.util.concurrent.TimeUnit

/**
 * Headless Android Auto Protocol (AAP) Receiver.
 * Connects directly to the Android Auto Developer Head Unit Server on 127.0.0.1:5277,
 * performs version negotiation, TLS authentication, service discovery, and extracts
 * the native 60 FPS H.264 video stream generated by Google's Android Auto GPU compositor.
 */
class AaHeadlessReceiver(
    private val context: Context,
    private val onH264Frame: (bytes: ByteArray, offset: Int, length: Int) -> Unit,
    private val onStatusChanged: (status: String) -> Unit
) {
    companion object {
        private const val TAG = "UmoxAaReceiver"
        private const val AA_SERVER_HOST = "127.0.0.1"
        private const val AA_SERVER_PORT = 5277

        // AAP Channels
        const val CH_CONTROL = 0
        const val CH_SENSOR = 1
        const val CH_VIDEO = 2
        const val CH_INPUT = 3
        const val CH_AUDIO_MEDIA = 4
        const val CH_AUDIO_GUIDANCE = 5

        // KeyCodes
        const val KEYCODE_BACK = 4
        const val KEYCODE_DPAD_UP = 19
        const val KEYCODE_DPAD_DOWN = 20
        const val KEYCODE_DPAD_LEFT = 21
        const val KEYCODE_DPAD_RIGHT = 22
        const val KEYCODE_DPAD_CENTER = 23
        const val KEYCODE_NAVIGATION = 65538 // Fullscreen Maps toggle
    }

    @Volatile
    var isRunning: Boolean = false
        private set

    @Volatile
    var isInputBound: Boolean = false
        private set

    private var socket: Socket? = null
    private var outputStream: OutputStream? = null
    private var tlsEngine: AaTlsEngine? = null
    private var isTlsActive: Boolean = false
    private var isAuthCompleteSent: Boolean = false

    private val writeLock = Any()
    private var executor: ScheduledExecutorService? = null
    private var videoSessionId: Int = 0
    private var lastAckTimeMs: Long = 0
    private var mediaMessageCount: Long = 0

    private val fragmentAssembler = AaFragmentAssembler()

    fun start() {
        if (isRunning) return
        isRunning = true
        Thread({ runReceiverLoop() }, "UmoxAaReceiver").start()
    }

    fun stop() {
        if (!isRunning) return
        log("Hentikan receiver diminta...")
        isRunning = false
        try {
            if (isTlsActive) {
                // Send ByeBye request (type 15)
                val bye = AaProtoWriter().writeVarint(1, 1).toByteArray()
                sendMessage(CH_CONTROL, 0, 15, bye)
            }
        } catch (_: Exception) {}

        try {
            socket?.close()
        } catch (_: Exception) {}

        executor?.shutdownNow()
        executor = null
    }

    private fun runReceiverLoop() {
        log("Menghubungkan ke Android Auto server di $AA_SERVER_HOST:$AA_SERVER_PORT...")
        executor = Executors.newSingleThreadScheduledExecutor()

        try {
            val s = Socket()
            socket = s
            s.tcpNoDelay = true
            s.connect(InetSocketAddress(AA_SERVER_HOST, AA_SERVER_PORT), 3000)
            s.soTimeout = 10000
            outputStream = s.getOutputStream()

            log("✔ Terhubung ke Android Auto server! Mengirim Version Request (1.1)...")
            // Send Version Request: channel 0, flags 0, type 1, payload [0, 1, 0, 1]
            sendMessage(CH_CONTROL, 0, 1, byteArrayOf(0, 1, 0, 1))

            val dis = DataInputStream(s.getInputStream())

            while (isRunning) {
                val channel = dis.readUnsignedByte()
                val flags = dis.readUnsignedByte()
                val length = dis.readUnsignedShort()

                if ((flags and 1) != 0 && (flags and 2) == 0) {
                    // First fragment of multi-frame message has 4-byte total length
                    dis.readInt()
                }

                var payload = ByteArray(length)
                dis.readFully(payload)

                if ((flags and 8) != 0) {
                    val tls = tlsEngine ?: throw IOException("Menerima paket terenkripsi sebelum TLS siap")
                    payload = tls.decrypt(payload)
                }

                val assembled = fragmentAssembler.assemble(channel, flags, payload)
                if (assembled != null && assembled.size >= 2) {
                    handleMessage(channel, assembled)
                }
            }
        } catch (e: ConnectException) {
            log("⚠ Server Android Auto belum aktif. Aktifkan 'Start head unit server' di Developer Settings.")
        } catch (e: SocketTimeoutException) {
            log(if (isTlsActive) "Android Auto berhenti merespon (timeout)" else "Android Auto tidak menjawab (timeout)")
        } catch (e: EOFException) {
            log("Koneksi Android Auto ditutup (EOF)")
        } catch (e: Exception) {
            if (isRunning) {
                log("Gangguan link Android Auto: ${e.message}")
            }
        } finally {
            isRunning = false
            executor?.shutdownNow()
            executor = null
            try {
                socket?.close()
            } catch (_: Exception) {}
            log("Sesi Android Auto berakhir (total pesan media: $mediaMessageCount)")
        }
    }

    private fun handleMessage(channel: Int, msg: ByteArray) {
        val type = ((msg[0].toInt() and 0xFF) shl 8) or (msg[1].toInt() and 0xFF)
        val payloadLen = msg.size - 2

        if (type == 7 && channel != 0) { // Channel open requested
            val openedCh = channel
            log("Saluran $openedCh dibuka oleh Android Auto")
            sendMessage(openedCh, 4, 8, makeStatusOk())
            return
        }

        when (channel) {
            CH_CONTROL -> handleControlMessage(type, msg, payloadLen)
            CH_SENSOR -> handleSensorMessage(type, msg, payloadLen)
            CH_VIDEO -> handleVideoMessage(type, msg, payloadLen)
            CH_INPUT -> handleInputMessage(type, msg, payloadLen)
            CH_AUDIO_MEDIA, CH_AUDIO_GUIDANCE -> handleAudioMessage(channel, type, msg, payloadLen)
        }
    }

    private fun handleControlMessage(type: Int, msg: ByteArray, len: Int) {
        when (type) {
            2 -> { // Version Response
                val major = ((msg[2].toInt() and 0xFF) shl 8) or (msg[3].toInt() and 0xFF)
                val minor = ((msg[4].toInt() and 0xFF) shl 8) or (msg[5].toInt() and 0xFF)
                val status = if (len >= 6) ((msg[6].toInt() and 0xFF) shl 8) or (msg[7].toInt() and 0xFF) else 0
                log("Versi protokol Android Auto: $major.$minor (status: $status)")
                if (status != 0) {
                    throw IOException("Versi protokol tidak cocok: $major.$minor")
                }

                tlsEngine = AaTlsEngine(context)
                val clientHello = tlsEngine!!.processHandshake(null)
                sendMessage(CH_CONTROL, 0, 3, clientHello)
                log("Handshake TLS dimulai...")
            }
            3 -> { // Encapsulated SSL (Handshake)
                val tlsBytes = ByteArray(len)
                System.arraycopy(msg, 2, tlsBytes, 0, len)
                val tls = tlsEngine ?: return
                val response = tls.processHandshake(tlsBytes)
                if (response.isNotEmpty()) {
                    sendMessage(CH_CONTROL, 0, 3, response)
                }
                if (tls.isHandshakeFinished && !isAuthCompleteSent) {
                    isAuthCompleteSent = true
                    isTlsActive = true
                    sendMessage(CH_CONTROL, 0, 4, makeStatusOk())
                    socket?.soTimeout = 0 // Remove timeout after TLS
                    log("✔ TLS Handshake selesai! Identitas head unit diterima.")
                }
            }
            5 -> { // Service Discovery Request
                log("Menerima Service Discovery dari ponsel. Mengirim kapabilitas HUD...")
                val response = buildServiceDiscoveryResponse()
                sendMessage(CH_CONTROL, 0, 6, response)
            }
            11 -> { // Ping Request
                val pingVal = AaProtoReader(msg, 2, len).getLong(1, 0)
                val reply = AaProtoWriter().writeVarint(1, pingVal).toByteArray()
                sendMessage(CH_CONTROL, 0, 12, reply)
            }
            12 -> { // Ping Response
            }
            13 -> { // Nav Focus Request
                val reply = AaProtoWriter().writeVarint(1, 2).toByteArray()
                sendMessage(CH_CONTROL, 0, 14, reply)
            }
            15 -> { // ByeBye Request
                sendMessage(CH_CONTROL, 0, 16, ByteArray(0))
                log("Android Auto mengakhiri sesi.")
                isRunning = false
            }
            16 -> { // ByeBye Response
                isRunning = false
            }
            18 -> { // Audio Focus Request
                val req = AaProtoReader(msg, 2, len).getInt(1, 1)
                val focusType = if (req != 4) 1 else 3
                val reply = AaProtoWriter()
                    .writeVarint(1, focusType)
                    .writeVarint(2, 0)
                    .toByteArray()
                sendMessage(CH_CONTROL, 0, 19, reply)
            }
        }
    }

    private fun handleSensorMessage(type: Int, msg: ByteArray, len: Int) {
        when (type) {
            32769 -> { // Sensor Start Request
                val sensorType = AaProtoReader(msg, 2, len).getInt(1, -1)
                sendMessage(CH_SENSOR, 0, 32770, makeStatusOk())
                if (sensorType == 13) { // Driving status
                    val data = AaProtoWriter()
                        .writeBytes(13, AaProtoWriter().writeVarint(1, 0).toByteArray())
                        .toByteArray()
                    sendMessage(CH_SENSOR, 0, 32771, data)
                } else if (sensorType == 10) { // Night mode
                    val data = AaProtoWriter()
                        .writeBytes(10, AaProtoWriter().writeVarint(1, 1).toByteArray())
                        .toByteArray()
                    sendMessage(CH_SENSOR, 0, 32771, data)
                }
                log("Sensor $sensorType dimulai")
            }
        }
    }

    private fun handleVideoMessage(type: Int, msg: ByteArray, len: Int) {
        when (type) {
            0 -> { // Video Data Frame (H.264)
                mediaMessageCount++
                if (mediaMessageCount == 1L) {
                    log("✔ Frame video pertama diterima dari Android Auto!")
                }
                // H.264 NALUs start at byte offset 10 (first 2 bytes = type 0x0000, next 8 bytes = timestamp)
                if (len > 8) {
                    val naluLen = msg.size - 10
                    onH264Frame(msg, 10, naluLen)
                }
                scheduleAck()
            }
            1 -> { // Codec Config (SPS / PPS)
                log("Konfigurasi codec (SPS/PPS) diterima dari Android Auto")
                val configLen = msg.size - 2
                onH264Frame(msg, 2, configLen)
                scheduleAck()
            }
            32768 -> { // Video Setup Request
                log("Video setup diminta oleh Android Auto...")
                sendMessage(CH_VIDEO, 0, 32771, makeVideoConfigOk())
                sendMessage(CH_VIDEO, 0, 32776, makeVideoFocusProjected(true))
            }
            32769 -> { // Video Start Request
                videoSessionId = AaProtoReader(msg, 2, len).getLong(1, 0).toInt()
                log("Video streaming aktif! (Session ID: $videoSessionId)")
                sendMessage(CH_VIDEO, 0, 32776, makeVideoFocusProjected(false))

                // Switch directly to fullscreen Google Maps after 2.5s
                executor?.schedule({
                    sendKey(KEYCODE_NAVIGATION)
                    log("Mengaktifkan Google Maps layar penuh secara otomatis.")
                }, 2500, TimeUnit.MILLISECONDS)
            }
            32770 -> { // Video Stop Request
                log("Video dihentikan oleh Android Auto.")
            }
            32775 -> { // Video Focus Request
                sendMessage(CH_VIDEO, 0, 32776, makeVideoFocusProjected(false))
            }
        }
    }

    private fun handleInputMessage(type: Int, msg: ByteArray, len: Int) {
        when (type) {
            32770 -> { // Key Binding Request
                sendMessage(CH_INPUT, 0, 32771, makeStatusOk())
                isInputBound = true
                log("✔ Kontrol tombol input terhubung!")
            }
        }
    }

    private fun handleAudioMessage(channel: Int, type: Int, msg: ByteArray, len: Int) {
        when (type) {
            32768 -> {
                sendMessage(channel, 0, 32771, makeVideoConfigOk())
            }
            32769 -> {
                // Audio started
            }
        }
    }

    fun sendKey(keyCode: Int) {
        if (!isInputBound) return
        try {
            val nowNanos = SystemClock.elapsedRealtimeNanos() / 1000
            sendMessage(CH_INPUT, 0, 32769, makeKeyEvent(nowNanos, keyCode, true))
            sendMessage(CH_INPUT, 0, 32769, makeKeyEvent(nowNanos + 50000, keyCode, false))
        } catch (e: Exception) {
            Log.w(TAG, "Gagal mengirim keycode $keyCode: ${e.message}")
        }
    }

    private fun scheduleAck() {
        val now = SystemClock.elapsedRealtime()
        val delay = Math.max(0L, (lastAckTimeMs + 100) - now)
        if (delay == 0L) {
            sendMediaAck()
        } else {
            executor?.schedule({ sendMediaAck() }, delay, TimeUnit.MILLISECONDS)
        }
    }

    private fun sendMediaAck() {
        if (!isRunning) return
        try {
            lastAckTimeMs = SystemClock.elapsedRealtime()
            val ack = AaProtoWriter()
                .writeVarint(1, videoSessionId)
                .writeVarint(2, 1)
                .toByteArray()
            sendMessage(CH_VIDEO, 0, 32772, ack)
        } catch (_: Exception) {}
    }

    fun sendMessage(channel: Int, flags: Int, type: Int, payload: ByteArray) {
        synchronized(writeLock) {
            val os = outputStream ?: throw IOException("Soket belum terhubung")

            var finalFlags = flags
            var body = ByteArray(payload.size + 2)
            body[0] = (type ushr 8).toByte()
            body[1] = type.toByte()
            System.arraycopy(payload, 0, body, 2, payload.size)

            if (isTlsActive && tlsEngine != null) {
                body = tlsEngine!!.encrypt(body)
                finalFlags = finalFlags or 8
            }

            // Framing: 4-byte header
            // byte 0: channel
            // byte 1: flags | 3 (FIRST_FRAME | LAST_FRAME)
            // byte 2-3: big-endian length
            if (body.size > 65535) {
                throw IllegalArgumentException("Ukuran payload melebihi 65535: ${body.size}")
            }
            val frame = ByteArray(body.size + 4)
            frame[0] = channel.toByte()
            frame[1] = (finalFlags or 3).toByte()
            frame[2] = (body.size ushr 8).toByte()
            frame[3] = body.size.toByte()
            System.arraycopy(body, 0, frame, 4, body.size)

            os.write(frame)
            os.flush()
        }
    }

    private fun buildServiceDiscoveryResponse(): ByteArray {
        // Channel 1: Sensors (Driving status 13, Night 10)
        val s13 = AaProtoWriter().writeVarint(1, 13).toByteArray()
        val s10 = AaProtoWriter().writeVarint(1, 10).toByteArray()
        val sensorSource = AaProtoWriter()
            .writeBytes(1, s13)
            .writeBytes(1, s10)
            .toByteArray()
        val ch1Service = AaProtoWriter()
            .writeVarint(1, CH_SENSOR)
            .writeBytes(2, sensorSource)
            .toByteArray()

        // Channel 2: Video Sink (H.264 Baseline, 800x480 resolution, 60 FPS, 160 DPI)
        val videoConfig = AaProtoWriter()
            .writeVarint(1, 1) // H264_BP
            .writeVarint(2, 2) // 800x480 resolution (optimum widescreen cluster)
            .writeVarint(3, 0) // margin width = 0
            .writeVarint(4, 0) // margin height = 0
            .writeVarint(5, 160) // 160 DPI
            .toByteArray()
        val mediaSinkVideo = AaProtoWriter()
            .writeVarint(1, 3) // Video
            .writeBytes(4, videoConfig)
            .writeVarint(5, 1) // Available while in call
            .toByteArray()
        val ch2Service = AaProtoWriter()
            .writeVarint(1, CH_VIDEO)
            .writeBytes(3, mediaSinkVideo)
            .toByteArray()

        // Channel 3: Input Sink (Handlebar buttons + Maps key)
        val keyCodes = intArrayOf(
            KEYCODE_BACK,
            KEYCODE_DPAD_UP,
            KEYCODE_DPAD_DOWN,
            KEYCODE_DPAD_LEFT,
            KEYCODE_DPAD_RIGHT,
            KEYCODE_DPAD_CENTER,
            KEYCODE_NAVIGATION
        )
        val inputSource = AaProtoWriter()
        for (kc in keyCodes) {
            inputSource.writeVarint(1, kc)
        }
        val ch3Service = AaProtoWriter()
            .writeVarint(1, CH_INPUT)
            .writeBytes(4, inputSource.toByteArray())
            .toByteArray()

        // Channel 4: Audio Media Sink
        val audioPcm = AaProtoWriter()
            .writeVarint(1, 16000)
            .writeVarint(2, 16)
            .writeVarint(3, 1)
            .toByteArray()
        val mediaSinkAudioMedia = AaProtoWriter()
            .writeVarint(1, 1)
            .writeVarint(2, 2)
            .writeBytes(3, audioPcm)
            .toByteArray()
        val ch4Service = AaProtoWriter()
            .writeVarint(1, CH_AUDIO_MEDIA)
            .writeBytes(3, mediaSinkAudioMedia)
            .toByteArray()

        // Channel 5: Audio Guidance Sink
        val mediaSinkAudioGuidance = AaProtoWriter()
            .writeVarint(1, 1)
            .writeBytes(2, audioPcm)
            .toByteArray()
        val ch5Service = AaProtoWriter()
            .writeVarint(1, CH_AUDIO_GUIDANCE)
            .writeBytes(5, mediaSinkAudioGuidance)
            .toByteArray()

        // Master Service Discovery Response
        return AaProtoWriter()
            .writeBytes(1, ch1Service)
            .writeBytes(1, ch2Service)
            .writeBytes(1, ch3Service)
            .writeBytes(1, ch4Service)
            .writeBytes(1, ch5Service)
            .writeString(2, "Yamaha")
            .writeString(3, "NMAX")
            .writeString(4, "2024")
            .writeString(5, "UMOX-DASHCONNECT")
            .writeVarint(6, 1)
            .writeString(7, "UMOX")
            .writeString(8, "DashConnect")
            .writeString(9, "1")
            .writeString(10, "1.0")
            .writeVarint(11, 0)
            .toByteArray()
    }

    private fun makeStatusOk(): ByteArray {
        return AaProtoWriter().writeVarint(1, 0).toByteArray()
    }

    private fun makeVideoConfigOk(): ByteArray {
        return AaProtoWriter()
            .writeVarint(1, 2)
            .writeVarint(2, 1)
            .writeVarint(3, 0)
            .toByteArray()
    }

    private fun makeVideoFocusProjected(unrequested: Boolean): ByteArray {
        return AaProtoWriter()
            .writeVarint(1, 1) // Mode: PROJECTED
            .writeVarint(2, if (unrequested) 1 else 0)
            .toByteArray()
    }

    private fun makeKeyEvent(timestampUs: Long, keyCode: Int, isDown: Boolean): ByteArray {
        val keyEvent = AaProtoWriter()
            .writeVarint(1, keyCode)
            .writeVarint(2, if (isDown) 1 else 0)
            .writeVarint(3, 0)
            .writeVarint(4, 0)
            .toByteArray()

        val wrapper = AaProtoWriter()
            .writeBytes(1, keyEvent)
            .toByteArray()

        return AaProtoWriter()
            .writeVarint(1, timestampUs)
            .writeBytes(4, wrapper)
            .toByteArray()
    }

    private fun log(msg: String) {
        Log.i(TAG, msg)
        onStatusChanged(msg)
    }
}

/**
 * Reassembles multi-fragment AAP frames.
 */
class AaFragmentAssembler {
    private val channelBuffers = HashMap<Int, ByteArrayOutputStream>()

    fun assemble(channel: Int, flags: Int, data: ByteArray): ByteArray? {
        val isFirst = (flags and 1) != 0
        val isLast = (flags and 2) != 0

        if (isFirst && isLast) {
            channelBuffers.remove(channel)
            return data
        }

        var stream = channelBuffers[channel]
        if (isFirst || stream == null) {
            stream = ByteArrayOutputStream(data.size * 4)
            channelBuffers[channel] = stream
        }

        stream.write(data, 0, data.size)

        if (!isLast) {
            return null
        }

        channelBuffers.remove(channel)
        return stream.toByteArray()
    }
}
